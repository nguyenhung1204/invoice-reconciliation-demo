import React, { useEffect, useMemo, useState } from 'react';
import { ArrowDownLeft, ArrowUpRight, LockKeyhole, Pencil, Plus, Receipt, Trash2, Wallet, X } from 'lucide-react';
import type { UserProfile } from '../../types/index.ts';
import { formatCurrencyVND } from '../../utils/matchingEngine.ts';
import { api, VoucherDTO } from '../../services/api.ts';

type VoucherType = 'THU' | 'CHI';
interface Voucher {
  id: string;
  backendId: number;
  voucherType: VoucherType;
  date: string;
  relatedPartyName: string;
  relatedInvoiceId?: string;
  content: string;
  amount: number;
  isAutoGenerated: boolean;
}
interface Draft {
  voucherType: VoucherType;
  date: string;
  relatedPartyName: string;
  content: string;
  amount: string;
}

const blankDraft = (voucherType: VoucherType = 'THU'): Draft => ({
  voucherType,
  date: new Date().toISOString().slice(0, 10),
  relatedPartyName: '',
  content: '',
  amount: '',
});

export const AccountingLedgerModule: React.FC<{ currentUser: UserProfile }> = ({ currentUser }) => {
  const [vouchers, setVouchers] = useState<Voucher[]>([]);
  const [filter, setFilter] = useState<'ALL' | VoucherType>('ALL');
  const [draft, setDraft] = useState<Draft | null>(null);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(true);
  const [isSaving, setIsSaving] = useState(false);
  const canManage = currentUser.role === 'ADMIN' || currentUser.role === 'CHIEF_ACCOUNTANT';

  const adaptVoucher = (row: VoucherDTO): Voucher => ({
    id: row.voucher_number,
    backendId: row.id,
    voucherType: row.voucher_type,
    date: row.voucher_date,
    relatedPartyName: row.related_party_name,
    relatedInvoiceId: row.related_invoice_id ? String(row.related_invoice_id) : undefined,
    content: row.content,
    amount: row.amount,
    isAutoGenerated: row.is_auto_generated,
  });

  useEffect(() => {
    let active = true;
    api.listAccountingVouchers().then((rows) => {
      if (active) setVouchers(rows.map(adaptVoucher));
    }).catch((cause: unknown) => {
      if (active) setError(cause instanceof Error ? `Không tải được sổ thu chi: ${cause.message}` : 'Không tải được sổ thu chi.');
    }).finally(() => {
      if (active) setLoading(false);
    });
    return () => { active = false; };
  }, []);

  const visibleVouchers = useMemo(
    () => vouchers.filter((voucher) => filter === 'ALL' || voucher.voucherType === filter),
    [filter, vouchers],
  );
  const activeVouchers = vouchers;
  const totalIn = activeVouchers.filter((voucher) => voucher.voucherType === 'THU').reduce((sum, voucher) => sum + voucher.amount, 0);
  const totalOut = activeVouchers.filter((voucher) => voucher.voucherType === 'CHI').reduce((sum, voucher) => sum + voucher.amount, 0);
  const openingBalance = 0;

  const startNew = (voucherType: VoucherType) => {
    setEditingId(null);
    setDraft(blankDraft(voucherType));
    setError('');
  };

  const saveDraft = async (event: React.FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    if (!draft || !draft.relatedPartyName.trim() || !draft.content.trim() || Number(draft.amount) <= 0) {
      setError('Vui lòng nhập đối tượng, nội dung và số tiền lớn hơn 0.');
      return;
    }
    setIsSaving(true);
    try {
      const payload = {
        voucher_type: draft.voucherType,
        voucher_date: draft.date,
        related_party_name: draft.relatedPartyName.trim(),
        related_invoice_id: null,
        content: draft.content.trim(),
        amount: Number(draft.amount),
      };
      const existing = vouchers.find((item) => item.id === editingId);
      if (editingId && !existing) throw new Error('Không tìm thấy phiếu cần cập nhật.');
      const saved = editingId
        ? await api.updateAccountingVoucher(existing!.backendId, payload)
        : await api.createAccountingVoucher(payload);
      const voucher = adaptVoucher(saved);
      setVouchers((current) => editingId ? current.map((item) => item.id === editingId ? voucher : item) : [voucher, ...current]);
      setDraft(null);
      setEditingId(null);
      setError('');
    } catch (cause) {
      setError(cause instanceof Error ? `Không lưu được phiếu: ${cause.message}` : 'Không lưu được phiếu.');
    } finally {
      setIsSaving(false);
    }
  };

  const deleteVoucher = async (voucher: Voucher) => {
    try {
      await api.deleteAccountingVoucher(voucher.backendId);
      setVouchers((items) => items.filter((item) => item.backendId !== voucher.backendId));
      setError('');
    } catch (cause) {
      setError(cause instanceof Error ? `Không xóa được phiếu ${voucher.id}: ${cause.message}` : `Không xóa được phiếu ${voucher.id}.`);
    }
  };

  const editVoucher = (voucher: Voucher) => {
    setEditingId(voucher.id);
    setDraft({ voucherType: voucher.voucherType, date: voucher.date, relatedPartyName: voucher.relatedPartyName, content: voucher.content, amount: String(voucher.amount) });
    setError('');
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="flex items-center gap-2 text-xl font-bold text-slate-900"><Wallet className="h-6 w-6 text-blue-600" />Sổ sách Kế toán Thu - Chi</h1>
          <p className="mt-1 text-xs text-slate-500">Theo dõi dòng tiền và các phiếu thu, chi.</p>
        </div>
        {canManage && <div className="flex gap-2">
          <button onClick={() => startNew('THU')} className="inline-flex items-center gap-1.5 rounded-lg bg-emerald-600 px-3 py-2 text-xs font-semibold text-white hover:bg-emerald-700"><Plus className="h-4 w-4" />Lập Phiếu Thu</button>
          <button onClick={() => startNew('CHI')} className="inline-flex items-center gap-1.5 rounded-lg bg-rose-600 px-3 py-2 text-xs font-semibold text-white hover:bg-rose-700"><Plus className="h-4 w-4" />Lập Phiếu Chi</button>
        </div>}
      </div>

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {[
          ['Quỹ đầu kỳ', openingBalance, 'bg-slate-50 text-slate-700'],
          ['Tổng Thu', totalIn, 'bg-emerald-50 text-emerald-700'],
          ['Tổng Chi', totalOut, 'bg-rose-50 text-rose-700'],
          ['Tồn quỹ cuối kỳ', openingBalance + totalIn - totalOut, 'bg-blue-50 text-blue-700'],
        ].map(([label, amount, color]) => (
          <div key={String(label)} className={`rounded-xl border border-slate-200 p-4 ${color}`}>
            <div className="text-xs font-medium opacity-80">{label}</div>
            <div className="mt-2 text-lg font-bold">{formatCurrencyVND(Number(amount))}</div>
          </div>
        ))}
      </div>

      {error && !draft && <p className="rounded-lg border border-rose-200 bg-rose-50 p-3 text-xs text-rose-800" role="alert">{error}</p>}

      {draft && (
        <section className="rounded-xl border border-blue-200 bg-white p-4 shadow-sm">
          <div className="mb-3 flex items-center justify-between">
            <h2 className="text-sm font-bold text-slate-900">{editingId ? 'Chỉnh sửa phiếu' : `Lập Phiếu ${draft.voucherType === 'THU' ? 'Thu' : 'Chi'} mới`}</h2>
            <button aria-label="Đóng biểu mẫu" onClick={() => setDraft(null)} className="rounded p-1 text-slate-500 hover:bg-slate-100"><X className="h-4 w-4" /></button>
          </div>
          <form onSubmit={saveDraft} className="grid gap-3 md:grid-cols-2 xl:grid-cols-5">
            <select aria-label="Loại phiếu" value={draft.voucherType} onChange={(event) => setDraft({ ...draft, voucherType: event.target.value as VoucherType })} className="rounded-lg border border-slate-300 p-2 text-xs">
              <option value="THU">Phiếu Thu</option><option value="CHI">Phiếu Chi</option>
            </select>
            <input aria-label="Ngày phiếu" type="date" required value={draft.date} onChange={(event) => setDraft({ ...draft, date: event.target.value })} className="rounded-lg border border-slate-300 p-2 text-xs" />
            <input aria-label="Đối tượng" required placeholder="Tên khách hàng / nhà cung cấp" value={draft.relatedPartyName} onChange={(event) => setDraft({ ...draft, relatedPartyName: event.target.value })} className="rounded-lg border border-slate-300 p-2 text-xs" />
            <input aria-label="Nội dung giao dịch" required placeholder="Nội dung giao dịch" value={draft.content} onChange={(event) => setDraft({ ...draft, content: event.target.value })} className="rounded-lg border border-slate-300 p-2 text-xs" />
            <div className="flex gap-2"><input aria-label="Số tiền" required type="number" min="1" placeholder="Số tiền" value={draft.amount} onChange={(event) => setDraft({ ...draft, amount: event.target.value })} className="min-w-0 flex-1 rounded-lg border border-slate-300 p-2 text-xs" /><button disabled={isSaving} className="rounded-lg bg-blue-600 px-3 text-xs font-semibold text-white disabled:cursor-wait disabled:opacity-60">{isSaving ? 'Đang lưu…' : 'Lưu phiếu'}</button></div>
          </form>
          {error && <p className="mt-2 text-xs text-rose-600" role="alert">{error}</p>}
        </section>
      )}

      <section className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-sm">
        <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 p-4">
          <div><h2 className="flex items-center gap-2 text-sm font-bold text-slate-900"><Receipt className="h-4 w-4 text-blue-600" />Danh sách Phiếu Thu - Chi ({visibleVouchers.length})</h2></div>
          <select aria-label="Lọc loại phiếu" value={filter} onChange={(event) => setFilter(event.target.value as typeof filter)} className="rounded-lg border border-slate-200 bg-white px-3 py-2 text-xs"><option value="ALL">Tất cả phiếu</option><option value="THU">Phiếu Thu</option><option value="CHI">Phiếu Chi</option></select>
        </div>
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-slate-50 text-[10px] uppercase tracking-wide text-slate-500"><tr><th className="px-4 py-3">Mã phiếu</th><th className="px-3 py-3">Ngày</th><th className="px-3 py-3">Loại</th><th className="px-3 py-3">Đối tượng / liên kết</th><th className="px-3 py-3">Nội dung</th><th className="px-3 py-3 text-right">Số tiền</th><th className="px-4 py-3 text-right">Thao tác</th></tr></thead>
            <tbody className="divide-y divide-slate-100">
              {loading && <tr><td colSpan={7} className="py-12 text-center text-slate-500">Đang tải dữ liệu từ máy chủ…</td></tr>}
              {visibleVouchers.map((voucher) => <tr key={voucher.id} className="hover:bg-slate-50">
                <td className="px-4 py-3 font-mono font-bold text-slate-800">{voucher.id}</td><td className="px-3 py-3 font-mono text-slate-600">{voucher.date}</td>
                <td className="px-3 py-3"><span className={`inline-flex items-center gap-1 rounded-full px-2 py-1 text-[10px] font-bold ${voucher.voucherType === 'THU' ? 'bg-emerald-50 text-emerald-700' : 'bg-rose-50 text-rose-700'}`}>{voucher.voucherType === 'THU' ? <ArrowDownLeft className="h-3 w-3" /> : <ArrowUpRight className="h-3 w-3" />}{voucher.voucherType === 'THU' ? 'Phiếu Thu' : 'Phiếu Chi'}</span></td>
                <td className="px-3 py-3 text-slate-700">{voucher.relatedPartyName}{voucher.relatedInvoiceId && <div className="mt-0.5 font-mono text-[10px] text-blue-600">HĐ: {voucher.relatedInvoiceId}</div>}</td><td className="max-w-[280px] px-3 py-3 text-slate-600">{voucher.content}</td>
                <td className={`px-3 py-3 text-right font-mono font-bold ${voucher.voucherType === 'THU' ? 'text-emerald-700' : 'text-rose-700'}`}>{voucher.voucherType === 'THU' ? '+' : '−'}{formatCurrencyVND(voucher.amount)}</td>
                <td className="px-4 py-3"><div className="flex justify-end gap-1">{canManage && !voucher.isAutoGenerated ? <><button aria-label={`Sửa ${voucher.id}`} onClick={() => editVoucher(voucher)} className="rounded p-1.5 text-blue-700 hover:bg-blue-50"><Pencil className="h-3.5 w-3.5" /></button><button aria-label={`Xóa ${voucher.id}`} onClick={() => window.confirm(`Xóa phiếu ${voucher.id}?`) && void deleteVoucher(voucher)} className="rounded p-1.5 text-rose-600 hover:bg-rose-50"><Trash2 className="h-3.5 w-3.5" /></button></> : <span title="Phiếu tự sinh hoặc vai trò hiện tại không được chỉnh sửa" className="inline-flex items-center gap-1 px-1 text-[10px] text-slate-400"><LockKeyhole className="h-3 w-3" />Khóa</span>}</div></td>
              </tr>)}
              {!loading && visibleVouchers.length === 0 && <tr><td colSpan={7} className="py-12 text-center text-slate-400 font-medium">Chưa có phiếu thu hoặc chi nào được ghi nhận.</td></tr>}
            </tbody>
          </table>
        </div>
      </section>
    </div>
  );
};
